"""Going live in about ten minutes once GAJAN's test environment arrives.

  igops setup    asks for each real value (secrets with hidden input, straight into the
                 vault), rewrites config/brand.toml with no secrets in it, and switches to live
  igops doctor   lists every remaining placeholder or missing access, each with the fix
"""
from __future__ import annotations

import getpass
import json
import tomllib
from pathlib import Path

from .config import load
from .vault import open_vault, ref

PLACEHOLDER_MARKERS = (".example", "northwind", "CHANGE")

FIELDS = [  # (key, question, section)
    ("brand.key", "Short brand key, lowercase, no spaces", "brand"),
    ("brand.name", "Brand display name", "brand"),
    ("brand.company_domain", "Test company email domain", "brand"),
    ("brand.website", "Brand website (profile link)", "brand"),
    ("brand.category", "Instagram category", "brand"),
    ("brand.bio", "Bio, 150 characters max", "brand"),
    ("brand.profile_image", "Path to the profile image from the brand kit", "brand"),
    ("ops.owner", "Owner of human tasks (email)", "ops"),
    ("ops.escalate_to", "Escalation contact (email)", "ops"),
    ("company_contacts.phone", "Company-controlled phone number", "company_contacts"),
    ("meta.business_id", "Meta business id", "meta"),
    ("proxy_policy.neutral_endpoint", "Neutral test endpoint URL", "proxy_policy"),
    ("vault.backend", "Vault backend: local, hashicorp or 1password", "vault"),
]

SECRETS = [  # (ref suffix, question, required)
    ("meta/system_user_token", "Meta system-user token", True),
    ("proxy/a", "Proxy A as http://user:pass@host:port", True),
    ("proxy/b", "Proxy B as http://user:pass@host:port", True),
    ("notify/smtp", "SMTP URL smtps://user:pass@host:465/from@domain (Enter to skip)", False),
]


def _current(raw: dict, key: str):
    sec, name = key.split(".", 1)
    if key == "company_contacts.phone":
        return (raw.get("company_contacts", {}).get("phones") or [""])[0]
    return raw.get(sec, {}).get(name, "")


def _q(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def render(v: dict, people: list[dict], vault: dict) -> str:
    """Write config/brand.toml. Only non-secret values and vault references."""
    b, d = v["brand.key"], v["brand.company_domain"]
    lines = [
        "# Generated by `igops setup`. No secrets: only vault references.",
        'mode = "live"', "",
        "[brand]", f"key = {_q(b)}", f"name = {_q(v['brand.name'])}", f"company_domain = {_q(d)}",
        f"website = {_q(v['brand.website'])}", f"category = {_q(v['brand.category'])}",
        f"bio = {_q(v['brand.bio'])}", f"profile_image = {_q(v['brand.profile_image'])}", "",
        "[vault]", *[f"{k} = {_q(str(x))}" for k, x in vault.items()], "",
        "[ops]", f"owner = {_q(v['ops.owner'])}", f"escalate_to = {_q(v['ops.escalate_to'])}",
        "signup_due_hours = 24", "task_due_hours = 24", "stale_access_days = 90", "stale_verification_days = 7", "",
        "[company_contacts]", f"phones = [{_q(v['company_contacts.phone'])}]", "",
        "[meta]", f"business_id = {_q(v['meta.business_id'])}", 'ig_user_id = ""',
        f'token_ref = "vault://{b}/meta/system_user_token"', "",
    ]
    for p in people:
        lines += ["[[people]]", f"email = {_q(p['email'])}", f"name = {_q(p['name'])}"]
        if p.get("test_member"):
            lines += ["test_member = true", 'vault_access = ["password", "backup_codes"]']
        lines += ["roles = { " + ", ".join(f"{k} = {_q(r)}" for k, r in p["roles"].items()) + " }", ""]
    for n in ("a", "b"):
        lines += ["[[proxies]]", f'name = "proxy-{n}"', f'url_ref = "vault://{b}/proxy/{n}"']
    lines += ["", "[proxy_policy]", f"neutral_endpoint = {_q(v['proxy_policy.neutral_endpoint'])}",
              "connect_timeout_s = 3", "read_timeout_s = 5", "max_retries = 3", "health_interval_s = 60", ""]
    return "\n".join(lines)


def setup(config_path: str = "config/brand.toml", state_dir: str = "state", ask=input, ask_secret=None) -> Path:
    ask_secret = ask_secret or (lambda q: getpass.getpass(q + " (hidden): "))
    path = Path(config_path)
    raw = tomllib.loads(path.read_text())
    print("Press Enter to keep the value in brackets. Secrets are hidden and go straight to the vault.\n")
    v = {}
    for key, question, _ in FIELDS:
        cur = _current(raw, key) or ("local" if key == "vault.backend" else "")
        got = ask(f"{question} [{cur}]: ").strip()
        v[key] = got or cur
    vault = {"backend": v["vault.backend"]}
    if vault["backend"] == "hashicorp":
        vault["address"] = ask("HashiCorp Vault address: ").strip()
        vault["mount"] = ask("KV mount [secret]: ").strip() or "secret"
    elif vault["backend"] == "1password":
        vault["op_vault"] = ask("1Password vault name: ").strip()
    d = v["brand.company_domain"]
    people = []
    for label, role, test in (("Owner", "admin", False), ("Content editor", "content_editor", False),
                              ("Temporary tester (offboarding test)", "insights_viewer", True)):
        default = v["ops.owner"] if label == "Owner" else ""
        email = ask(f"{label} email on @{d} [{default}]: ").strip() or default
        if email:
            people.append({"email": email, "name": label, "roles": {"business_suite": role}, "test_member": test})
    text = render(v, people, vault)
    backup = path.with_suffix(".toml.bak")
    backup.write_text(path.read_text())
    path.write_text(text)
    load(path)                                       # validate before storing secrets
    vlt = open_vault(vault, Path(state_dir))
    for suffix, question, required in SECRETS:
        r = ref(v["brand.key"], *suffix.split("/"))
        if vlt.exists(r) and ask(f"{r} already set. Replace? [y/N]: ").strip().lower() != "y":
            continue
        val = ask_secret(question).strip()
        if val:
            vlt.put(r, val, meta={"set_by": "setup"})
            print(f"  stored {r}")
        elif required:
            print(f"  skipped {r}: `igops doctor` will list it as missing")
    print(f"\nWrote {path} (previous version saved to {backup}). Next: `igops doctor`.")
    return path


def doctor(app) -> list[dict]:
    """Every check that stands between this checkout and a real run, with the fix."""
    cfg, v = app.cfg, app.vault
    rows = []

    def check(name, ok, detail, fix=""):
        rows.append({"check": name, "ok": bool(ok), "detail": detail, "fix": "" if ok else fix})

    raw_text = Path(cfg.path).read_text() if Path(cfg.path).exists() else ""
    placeholders = [m for m in PLACEHOLDER_MARKERS if m in raw_text]
    check("mode is live", not cfg.simulation, f"mode = {cfg.mode}", "run `igops setup`")
    check("no placeholder values in config", not placeholders,
          "placeholders found: " + ", ".join(placeholders) if placeholders else "none", "run `igops setup`")
    check("vault backend", True, cfg.vault.get("backend", "local"))
    for name, r in (("Meta token in vault", cfg.meta_token_ref),
                    *[(f"{p['name']} credentials in vault", p["url_ref"]) for p in cfg.proxies]):
        try:
            present = v.exists(r)
        except Exception as exc:   # noqa: BLE001
            present, r = False, f"{r} ({type(exc).__name__})"
        check(name, present, r, f"`igops vault put {r} --prompt`")
    check("Meta business id", bool(cfg.meta_business_id), cfg.meta_business_id or "empty", "run `igops setup`")
    check("profile image file", Path(cfg.profile_image).is_file(), cfg.profile_image,
          "put the brand-kit image at this path")
    if not cfg.simulation and v.exists(cfg.meta_token_ref):
        try:
            me = app.meta.me()
            check("Meta token works", True, f"token belongs to {me.get('name', me.get('id'))}")
        except Exception as exc:   # noqa: BLE001
            check("Meta token works", False, type(exc).__name__ + ": " + str(exc)[:120], "check the token's scopes")
    if all(v.exists(p["url_ref"]) for p in cfg.proxies) and cfg.proxies:
        from .proxy import ProxyPool
        pool = ProxyPool(cfg.proxies, v, app.log, cfg.proxy_policy)
        for name, ok in pool.check_all().items():
            check(f"{name} health", ok, cfg.proxy_policy.get("neutral_endpoint", ""), "check the proxy and endpoint")
    return rows
